import '../../schema/schema.dart';
import 'backend_core.dart';

/// Deployment targets for the generated write-upload backend.
enum BackendTarget {
  vercel('Vercel Functions', 'vercel'),
  supabase('Supabase Edge Functions', 'supabase'),
  cloudflare('Cloudflare Workers (experimental)', 'cloudflare');

  const BackendTarget(this.label, this.id);

  final String label;
  final String id;
}

/// Generates the backend project for [target]: relative path → file content.
Map<String, String> generateBackendFiles(
    MongoEasySchema schema, BackendTarget target) {
  return switch (target) {
    BackendTarget.vercel => _vercel(schema),
    BackendTarget.supabase => _supabase(schema),
    BackendTarget.cloudflare => _cloudflare(schema),
  };
}

const _envDocs = '''
| Variable | Required | Description |
|---|---|---|
| `MONGO_URI` | yes | MongoDB Atlas connection string (Database → Connect → Drivers). |
| `MONGO_DB` | yes | Database name to write to. |
| `AUTH_MODE` | no | `dev` (default, HS256 shared secret + /token endpoint) or `jwks` (production). |
| `JWT_SECRET` | dev mode | Shared HS256 secret — configure the SAME value in PowerSync (Instance → Client Auth → HS256). Min 32 chars. |
| `JWKS_URL` | jwks mode | Your auth provider's JWKS endpoint (Supabase/Firebase/Auth0). |
| `JWT_AUDIENCE` | no | Expected `aud` claim; use your PowerSync instance URL. |

**Security notes**
- The upload endpoint verifies the same JWT your app sends to PowerSync and
  enforces per-user ownership server-side (owner fields are assigned from the
  token, never trusted from the client).
- `AUTH_MODE=dev` exposes `/token`, which signs a JWT for any email — dev
  only. Switch to `AUTH_MODE=jwks` with a real auth provider before launch.
''';

