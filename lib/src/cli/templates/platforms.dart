Map<String, String> _supabase(MongoEasySchema schema) {
  final core = renderBackendCore(
    schema,
    imports: "import { MongoClient, ObjectId } from 'npm:mongodb@6';\n"
        "import { jwtVerify, createRemoteJWKSet, SignJWT } from 'npm:jose@5';",
  );

  return {
    'functions/_shared/core.ts': core,
    'functions/upload/index.ts': '''
import { handleUpload, readEnv } from '../_shared/core.ts';

Deno.serve((request) =>
  handleUpload(request, readEnv((key) => Deno.env.get(key))));
''',
    'functions/token/index.ts': '''
import { handleToken, readEnv } from '../_shared/core.ts';

Deno.serve((request) =>
  handleToken(request, readEnv((key) => Deno.env.get(key))));
''',
    'README.md': '''
# mongo_easy backend — Supabase Edge Functions

Generated by `dart run mongo_easy:setup`. Two functions:

- `upload` — applies client writes to MongoDB (JWT-protected)
- `token` — dev-only login (disabled when `AUTH_MODE=jwks`)

## Deploy

```bash
supabase functions deploy upload --no-verify-jwt
supabase functions deploy token --no-verify-jwt
```

(`--no-verify-jwt` is required: these functions verify the PowerSync JWT
themselves, which is not a Supabase-issued token unless you use Supabase
Auth.)

Set secrets:

```bash
supabase secrets set MONGO_URI='mongodb+srv://...' MONGO_DB=mydb \\
  AUTH_MODE=dev JWT_SECRET='<32+ char secret>' \\
  JWT_AUDIENCE='https://<instance>.powersync.journeyapps.com'
```

$_envDocs

Your app's `uploadUrl` is
`https://<project-ref>.supabase.co/functions/v1/upload`; the dev token
endpoint is `https://<project-ref>.supabase.co/functions/v1/token`.
''',
  };
}

Map<String, String> _cloudflare(MongoEasySchema schema) {
  final core = renderBackendCore(
    schema,
    imports: "import { MongoClient, ObjectId } from 'mongodb';\n"
        "import { jwtVerify, createRemoteJWKSet, SignJWT } from 'jose';",
  );

  return {
    'src/core.ts': core,
    'src/index.ts': '''
import { handleUpload, handleToken, type Env as CoreEnv } from './core';

interface WorkerEnv extends Record<string, string | undefined> {}

export default {
  async fetch(request: Request, env: WorkerEnv): Promise<Response> {
    const url = new URL(request.url);
    const coreEnv: CoreEnv = {
      MONGO_URI: env.MONGO_URI ?? '',
      MONGO_DB: env.MONGO_DB ?? '',
      AUTH_MODE: env.AUTH_MODE ?? 'dev',
      JWT_SECRET: env.JWT_SECRET,
      JWKS_URL: env.JWKS_URL,
      JWT_AUDIENCE: env.JWT_AUDIENCE,
    };
    if (url.pathname === '/upload') return handleUpload(request, coreEnv);
    if (url.pathname === '/token') return handleToken(request, coreEnv);
    return new Response('not found', { status: 404 });
  },
};
''',
